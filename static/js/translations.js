let currentLang = "en";
try { currentLang = localStorage.getItem("catrank_lang") || "en"; } catch (_) {}
if (!["en", "ru"].includes(currentLang)) currentLang = "en";

function t(key, params = {}) {
    let dict = translations[currentLang] || translations["en"];
    let text = dict[key] || translations["en"][key] || key;
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return text;
}

function applyTranslations() {
    document.documentElement.lang = currentLang;

    // Never replace readable fallback text with a raw translation key.
    // This also protects the UI during deploys when an older cached JS file
    // is briefly mixed with newer HTML.
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (!key) return;

        const translated = t(key);
        if (!translated || translated === key) return;

        const textSpan = el.querySelector(':scope > span:not([aria-hidden])');
        if (textSpan) {
            textSpan.textContent = translated;
            return;
        }

        const hasVisualChild = el.querySelector(':scope > i, :scope > svg, :scope > img');
        if (!hasVisualChild) {
            el.textContent = translated;
            return;
        }

        // For controls that have an icon plus a direct text node, preserve
        // the icon and only replace the visible text.
        const textNode = Array.from(el.childNodes).find(node =>
            node.nodeType === Node.TEXT_NODE && node.textContent.trim()
        );
        if (textNode) textNode.textContent = ` ${translated}`;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (!key) return;
        const translated = t(key);
        if (translated && translated !== key) el.placeholder = translated;
    });

    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (!key) return;
        const translated = t(key);
        if (translated && translated !== key) el.title = translated;
    });
    const enBtns = document.querySelectorAll(".lang-btn-en");
    const ruBtns = document.querySelectorAll(".lang-btn-ru");
    
    enBtns.forEach(btn => {
        if (currentLang === "en") {
            btn.className = "lang-btn-en px-2.5 py-1 text-xs font-black bg-indigo-600 text-white rounded-lg shadow-sm transition cursor-default";
        } else {
            btn.className = "lang-btn-en px-2.5 py-1 text-xs font-bold text-slate-700 hover:text-indigo-600 hover:bg-slate-200/80 rounded-lg transition cursor-pointer";
        }
    });

    ruBtns.forEach(btn => {
        if (currentLang === "ru") {
            btn.className = "lang-btn-ru px-2.5 py-1 text-xs font-black bg-indigo-600 text-white rounded-lg shadow-sm transition cursor-default";
        } else {
            btn.className = "lang-btn-ru px-2.5 py-1 text-xs font-bold text-slate-700 hover:text-indigo-600 hover:bg-slate-200/80 rounded-lg transition cursor-pointer";
        }
    });
}

function setLanguage(lang) {
    if (!["en", "ru"].includes(lang)) return;
    currentLang = lang;
    try { localStorage.setItem("catrank_lang", lang); } catch (_) {}
    document.cookie = `catrank_lang=${lang}; path=/; max-age=31536000`;
    applyTranslations();
    window.dispatchEvent(new CustomEvent("catrank_language_changed", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
});
